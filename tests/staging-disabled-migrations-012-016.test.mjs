  assert.equal(NATIVE_ACCESS_APPROVED, false)
  assert.equal(PROJECT_REF, 'qdmvngjwkcsilzmqksme'); assert.equal(PRODUCTION_PROJECT_REF, 'wrhgscovsgsudtedbljr')
  assert.deepEqual(ENDPOINT, { hostname: 'api.supabase.com', path: '/v1/projects/qdmvngjwkcsilzmqksme/database/query', method: 'POST' })
  assert.equal(KEYCHAIN_SERVICE, 'Supabase CLI'); assert.equal(KEYCHAIN_ACCOUNT, 'supabase')
  const source = readFileSync('scripts/staging-disabled-migrations-012-016.mjs', 'utf8')
  assert.match(source, /export const NATIVE_ACCESS_APPROVED = false/)
  assert.doesNotMatch(source, /process\.argv\[[^]]+\].*(?:query|url|header|sql)/i)
  assert.match(source, /agent:\s*false/); assert.match(source, /maxRequests/) // source is reviewed alongside manifest below
  assert.match(FIXED_QUERY, /^-- GENERATED by scripts\/staging-disabled-migrations-012-016\.prepare\.mjs/m)
  const result = execFileSync(process.execPath, ['scripts/staging-disabled-migrations-012-016.mjs'], { encoding: 'utf8' })
  assert.deepEqual(JSON.parse(result), { status: 'NATIVE_ACCESS_DISABLED', target: PROJECT_REF, installId: INSTALL_ID })
