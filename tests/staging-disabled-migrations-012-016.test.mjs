test('the generated transaction pins every source and only removes their outer wrappers', () => {
  execFileSync(process.execPath, ['scripts/staging-disabled-migrations-012-016.prepare.mjs'], { stdio: 'pipe' })
  const pkg = buildPackage(), artifact = readFileSync('config/staging-disabled-migrations-012-016.sql', 'utf8')
  const manifest = JSON.parse(readFileSync('config/staging-disabled-migrations-012-016.json', 'utf8'))
  assert.equal(artifact, pkg.sql); assert.equal(manifest.transactionSha256, pkg.sqlSha256)
  assert.equal(manifest.nativeAccessApproved, false); assert.equal(manifest.sourcePinsForTransport.length, 2)
  execFileSync(process.execPath, ['scripts/staging-disabled-migrations-012-016.prepare.mjs', '--check'], { stdio: 'pipe' })
  assert.equal(pkg.sources.length, 5); assert.deepEqual(pkg.sources.map(source => source.version), MIGRATIONS.map(([version]) => version))
  assert.equal((artifact.match(/^BEGIN;$/gm) || []).length, 1); assert.equal((artifact.match(/^COMMIT;$/gm) || []).length, 1)
  assert.equal((artifact.match(/INSERT INTO tll_staging_private\.applied_migrations/g) || []).length, 1)
  for (const source of pkg.sources) {
    assert.match(artifact, new RegExp(source.sha256)); assert.match(artifact, new RegExp(source.version))
  }
  assert.match(artifact, /Exact 002--011 predecessor ledger required/)
  assert.match(artifact, /All controls must remain disabled/)
  assert.match(artifact, /Expected empty migration destination required/)
  assert.match(artifact, /Exact reviewed ADMIN-only owner authority required/)
  assert.match(artifact, /production is excluded/)
  assert.match(artifact, /tll_disabled_migration_postflight/)
})

test('only the redacted postflight receipt is accepted', () => {
  const result = validateResult([{ tll_disabled_migration_postflight: receipt }])
  assert.deepEqual(Object.keys(result).sort(), ['installId', 'migrationCount', 'status', 'target', 'transactionSha256'])
  assert.equal(result.status, 'PASS')
  assert.throws(() => validateResult([{ tll_disabled_migration_postflight: { ...receipt, controlsDisabled: false } }]))
  assert.throws(() => validateResult([{ tll_disabled_migration_postflight: { ...receipt, migrationCount: 4 } }]))
  assert.throws(() => validateResult([{ tll_disabled_migration_postflight: { ...receipt, rawRows: [] } }]))
})

