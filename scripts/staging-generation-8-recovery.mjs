#!/usr/bin/env node
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root=resolve(import.meta.dirname,'..')
const predecessor=Object.freeze({generation:6,windowId:'83888906-23fa-4653-a886-fe2733ed76a0'})
const successor=Object.freeze({generation:8,windowId:'c790120a-9d62-49f1-9fe4-0a10983fd114'})
const files=Object.freeze([
  Object.freeze({source:'config/staging-account-activation-recovery.sql',sourceSha256:'69b6cae3da32c62512008e14c3fb6c68746e9ee533a1dedcaa690ff349fea87c',output:'config/staging-generation-8-recovery.sql'}),
  Object.freeze({source:'config/staging-account-activation-recovery-postcommit.sql',sourceSha256:'278953bd725c9ccdba2e2da0faaafac76aafd94e65234e1fa0c62d68b1d78d35',output:'config/staging-generation-8-recovery-postcommit.sql'}),
])
const unavailable=()=>{throw new Error('Generation-8 recovery generation unavailable')}

function replaceRequired(value,from,to){if(!value.includes(from))unavailable();return value.replaceAll(from,to)}
function transform(value){
  value=replaceRequired(value,'-- GENERATED by scripts/staging-account-activation-recovery.mjs; do not edit.','-- GENERATED by scripts/staging-generation-8-recovery.mjs from the pinned generation-6 recovery; do not edit.')
  value=replaceRequired(value,`parsed->>'generation' IS DISTINCT FROM '${predecessor.generation}'`,`parsed->>'generation' IS DISTINCT FROM '${successor.generation}'`)
  if(value.includes(`'generation',${predecessor.generation}`))value=value.replaceAll(`'generation',${predecessor.generation}`,`'generation',${successor.generation}`)
  value=replaceRequired(value,predecessor.windowId,successor.windowId)
  if(value.includes(predecessor.windowId)||value.includes(`parsed->>'generation' IS DISTINCT FROM '${predecessor.generation}'`))unavailable()
  return value
}

const outputs=[]
for(const file of files){
  const source=await readFile(resolve(root,file.source),'utf8')
  if(createHash('sha256').update(source).digest('hex')!==file.sourceSha256)unavailable()
  outputs.push([resolve(root,file.output),transform(source)])
}
if(process.argv.includes('--check')){
  let stale=false
  for(const [path,expected] of outputs){let current='';try{current=await readFile(path,'utf8')}catch{}if(current!==expected)stale=true}
  if(stale){console.error('generation-8 recovery artifact is stale');process.exitCode=1}
}else for(const [path,content] of outputs)await writeFile(path,content,{mode:0o644})
