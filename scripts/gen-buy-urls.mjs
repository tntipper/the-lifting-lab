// gen-buy-urls.mjs
//
// Generates populate-buy-urls.sql from Path A's webapp/data.js.
//
// The live `products` table was seeded verbatim from data.js (see
// seed-from-path-a.ts), so brand+name match exactly between the two. This
// script extracts every Path A product whose prices[0].url is a DIRECT product
// page (not a retailer search) and emits idempotent UPDATE statements keyed on
// brand+name.
//
// A "direct" URL is any of:
//   - Shopify form:   https://{brand-domain}/products/{handle}
//   - Amazon product: https://www.amazon.co.uk/dp/{ASIN}
//   - MyProtein page: https://www.myprotein.com/p/...
// i.e. anything that is NOT a /s?k= / /search style query.
//
// Run:  node scripts/gen-buy-urls.mjs
//   (writes scripts/populate-buy-urls.sql; prints a match report to stdout)

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const DATA_JS = 'C:/Users/tobia/.openclaw/workspace/theliftinglab/webapp/data.js'
const OUT = resolve(ROOT, 'scripts', 'populate-buy-urls.sql')

// ---- load window.DADB ----
const dataSrc = readFileSync(DATA_JS, 'utf8')
const DADB = new Function('window', dataSrc + '\nreturn window.DADB;')({})

// A direct product page: has a path that is NOT a search endpoint.
function isDirect(url) {
  if (!url) return false
  const u = url.toLowerCase()
  if (/[?&](k|q|query|search)=/.test(u)) return false // search query string
  if (/\/s\b|\/search\b|search\.list/.test(u)) return false // search path
  return /\/products\/|\/dp\/|\/p\//.test(u) // known direct product patterns
}

// SQL string literal (single-quote escaped)
const sql = (s) => "'" + String(s).replace(/'/g, "''") + "'"

const rows = []
const skipped = []
for (const cat in DADB) {
  for (const p of DADB[cat].products || []) {
    const url = p.prices && p.prices.length ? p.prices[0].url : null
    if (!url) continue
    if (!isDirect(url)) {
      skipped.push(`${cat} | ${p.Brand} | ${p.Name} | ${url} (not direct)`)
      continue
    }
    rows.push({ cat, brand: p.Brand || '', name: p.Name || '', url })
  }
}

const lines = [
  '-- populate-buy-urls.sql',
  '-- GENERATED by scripts/gen-buy-urls.mjs — do not edit by hand.',
  '-- Sets products.buy_url to a verified DIRECT product page (deep-link).',
  '-- Source: Path A webapp/data.js prices[0].url. Match on brand+name (the live',
  '-- table was seeded verbatim from the same data, so these match exactly).',
  '-- Idempotent. Run AFTER add-buy-url.sql in the Supabase SQL Editor.',
  '',
]
for (const r of rows) {
  lines.push(
    `UPDATE public.products SET buy_url = ${sql(r.url)} WHERE brand = ${sql(r.brand)} AND name = ${sql(r.name)};`,
  )
}
lines.push('')
lines.push(`-- ${rows.length} direct URLs emitted.`)
lines.push('')

writeFileSync(OUT, lines.join('\n'))

console.log(`Wrote ${OUT}`)
console.log(`Direct URLs emitted: ${rows.length}`)
console.log(`Skipped (not direct / no price): ${skipped.length}`)
if (skipped.length) {
  console.log('--- skipped ---')
  console.log(skipped.join('\n'))
}
