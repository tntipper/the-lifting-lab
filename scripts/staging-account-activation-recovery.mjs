#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

// This is intentionally a fixed, secret-free retirement program. It is for a
// post-012--016 staging install only; it must never be pointed at production.
const root = resolve(import.meta.dirname, '..')
const output = resolve(root, 'config/staging-account-activation-recovery.sql')

const sql = `-- GENERATED by scripts/staging-account-activation-recovery.mjs; do not edit.
--
-- TLL staging unified-account emergency recovery, post migrations 012--016.
-- This is a one-way *retirement* action: it disables every account control,
-- holds or cancels active work, redacts revocable ciphertext using the reviewed
-- hold semantics, and retires only the five named runtime LOGIN roles. It does
-- not DELETE rows, DROP roles, modify auth.users, alter managed Supabase roles,
-- or enable an application, Edge function, provider, checkout or email flow.
--
-- Run only from the reviewed staging operator window after confirming project
-- qdmvngjwkcsilzmqksme and preserving a preflight fingerprint. Production
-- wrhgscovsgsudtedbljr is excluded. A failure rolls the entire transaction back.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='30s';

DO $preflight$
DECLARE r text;
BEGIN
  IF current_user<>session_user OR current_setting('server_version_num')::int<170000 THEN
    RAISE EXCEPTION 'Staging recovery requires one direct PostgreSQL 17 operator session';
  END IF;
  FOREACH r IN ARRAY ARRAY[
    'tll_customer_private.control','tll_cart_private.control','tll_broker_private.control',
    'tll_provisional_private.control','tll_bridge_private.control',
    'tll_customer_private.shopify_proofs','tll_cart_private.transitions',
    'tll_bridge_private.finalizations','tll_bridge_private.account_operations',
    'tll_bridge_private.account_logouts'
  ] LOOP
    IF to_regclass(r) IS NULL THEN RAISE EXCEPTION 'Recovery requires reviewed 012--016 relation: %',r; END IF;
  END LOOP;
  FOREACH r IN ARRAY ARRAY[
    'tll_customer_runtime','tll_cart_runtime','tll_broker_runtime',
    'tll_provisional_runtime','tll_bridge_runtime',
    'tll_customer_executor','tll_cart_gateway','tll_broker_executor',
    'tll_provisional_executor','tll_bridge_executor'
  ] LOOP
    IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname=r) THEN
      RAISE EXCEPTION 'Recovery role is absent: %',r;
    END IF;
  END LOOP;
  IF NOT EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid='tll_bridge_private.account_generations'::regclass
    AND attname='logout_session_id' AND NOT attisdropped)
    OR to_regprocedure('tll_bridge_private.account_logout_repository(text,jsonb)') IS NULL THEN
    RAISE EXCEPTION 'Recovery requires migration 016 account logout surface';
  END IF;
END $preflight$;

LOCK TABLE
  tll_customer_private.control,tll_cart_private.control,tll_broker_private.control,
  tll_provisional_private.control,tll_bridge_private.control,
  tll_customer_private.shopify_proofs,tll_cart_private.sessions,tll_cart_private.operations,
  tll_cart_private.transitions,tll_broker_private.flows,tll_provisional_private.intents,
  tll_bridge_private.grants,tll_bridge_private.finalizations,
  tll_bridge_private.account_generations,tll_bridge_private.account_operations
  IN SHARE ROW EXCLUSIVE MODE;

-- Close admission first. The direct writes use the same terminal shapes as the
-- reviewed repository hold/cancel paths and preserve rows and operation journals.
UPDATE tll_customer_private.control
  SET enabled=false,changed_at=clock_timestamp(),reason_code='recovery_retired';
UPDATE tll_cart_private.control SET enabled=false;
UPDATE tll_broker_private.control
  SET enabled=false,changed_at=clock_timestamp(),reason_code='recovery_retired';
UPDATE tll_provisional_private.control
  SET enabled=false,changed_at=clock_timestamp(),reason_code='recovery_retired';
UPDATE tll_bridge_private.control
  SET enabled=false,epoch=epoch+1,changed_at=clock_timestamp(),reason_code='recovery_retired';

UPDATE tll_customer_private.shopify_proofs
  SET state='held',fence=nextval('tll_customer_private.shopify_proof_fences'),
      attempt_material=NULL,receipt_id=NULL,shop_id=NULL,issuer=NULL,subject=NULL,
      verified_at=NULL,proof_expires_at=NULL,access_expires_at=NULL,tokens=NULL
  WHERE state<>'held';
UPDATE tll_cart_private.sessions SET phase='held',lease_until=NULL WHERE phase='working';
UPDATE tll_cart_private.operations SET state='held' WHERE state='working';
UPDATE tll_cart_private.transitions SET state='held',lease_until=NULL WHERE state='claimed';
UPDATE tll_broker_private.flows
  SET status='cancelled',generation=generation+1,fence=nextval('tll_broker_private.fences')
  WHERE status NOT IN ('held','cancelled');
UPDATE tll_provisional_private.intents
  SET state='cancelled',material=NULL,generation=generation+1,fence=nextval('tll_provisional_private.fences')
  WHERE state NOT IN ('held','cancelled');
UPDATE tll_bridge_private.grants SET state='cancelled',release_hash=NULL
  WHERE state NOT IN ('held','cancelled');
UPDATE tll_bridge_private.finalizations
  SET state='held',generation=generation+1,fence=nextval('tll_bridge_private.final_fences'),
      callback_material=NULL,provisional_material=NULL,user_id=NULL,identity_id=NULL,
      authenticated_at=NULL,checked_at=NULL,session_expires_at=NULL,session_material=NULL,reconciled_at=NULL
  WHERE state<>'held';
UPDATE tll_bridge_private.account_operations
  SET state='held',completed_at=COALESCE(completed_at,clock_timestamp())
  WHERE state IN ('claimed','completed');
UPDATE tll_bridge_private.account_generations
  SET generation=generation+1,logout_session_id=NULL,updated_at=clock_timestamp();

-- Runtime roles are preserved for postmortem identity, but no longer authenticate
-- or retain any role edge. PASSWORD NULL invalidates their password credentials.
DO $retire_runtime_roles$
DECLARE membership record; r text;
BEGIN
  FOREACH r IN ARRAY ARRAY[
    'tll_customer_runtime','tll_cart_runtime','tll_broker_runtime',
    'tll_provisional_runtime','tll_bridge_runtime'
  ] LOOP
    EXECUTE format('ALTER ROLE %I NOLOGIN PASSWORD NULL',r);
  END LOOP;
  -- Re-select one edge after each REVOKE. A cursor over pg_auth_members can
  -- skip a later row when its own catalog scan is changed mid-iteration.
  LOOP
    SELECT granted.rolname AS granted_role,member.rolname AS member_role INTO membership
    FROM pg_auth_members edge
    JOIN pg_roles granted ON granted.oid=edge.roleid
    JOIN pg_roles member ON member.oid=edge.member
    WHERE granted.rolname IN ('tll_customer_runtime','tll_cart_runtime','tll_broker_runtime','tll_provisional_runtime','tll_bridge_runtime')
       OR member.rolname IN ('tll_customer_runtime','tll_cart_runtime','tll_broker_runtime','tll_provisional_runtime','tll_bridge_runtime')
    ORDER BY granted.rolname,member.rolname LIMIT 1;
    EXIT WHEN NOT FOUND;
    EXECUTE format('REVOKE %I FROM %I',membership.granted_role,membership.member_role);
  END LOOP;
END $retire_runtime_roles$;

DO $postflight$
DECLARE r text;
BEGIN
  IF EXISTS(SELECT 1 FROM tll_customer_private.control WHERE enabled)
    OR EXISTS(SELECT 1 FROM tll_cart_private.control WHERE enabled)
    OR EXISTS(SELECT 1 FROM tll_broker_private.control WHERE enabled)
    OR EXISTS(SELECT 1 FROM tll_provisional_private.control WHERE enabled)
    OR EXISTS(SELECT 1 FROM tll_bridge_private.control WHERE enabled) THEN
    RAISE EXCEPTION 'Recovery failed to disable every account control';
  END IF;
  IF EXISTS(SELECT 1 FROM tll_customer_private.shopify_proofs WHERE state<>'held')
    OR EXISTS(SELECT 1 FROM tll_cart_private.sessions WHERE phase='working')
    OR EXISTS(SELECT 1 FROM tll_cart_private.operations WHERE state='working')
    OR EXISTS(SELECT 1 FROM tll_cart_private.transitions WHERE state='claimed')
    OR EXISTS(SELECT 1 FROM tll_broker_private.flows WHERE status NOT IN ('held','cancelled'))
    OR EXISTS(SELECT 1 FROM tll_provisional_private.intents WHERE state NOT IN ('held','cancelled'))
    OR EXISTS(SELECT 1 FROM tll_bridge_private.grants WHERE state NOT IN ('held','cancelled'))
    OR EXISTS(SELECT 1 FROM tll_bridge_private.finalizations WHERE state<>'held')
    OR EXISTS(SELECT 1 FROM tll_bridge_private.account_operations WHERE state IN ('claimed','completed')) THEN
    RAISE EXCEPTION 'Recovery left executable account work';
  END IF;
  FOREACH r IN ARRAY ARRAY[
    'tll_customer_runtime','tll_cart_runtime','tll_broker_runtime',
    'tll_provisional_runtime','tll_bridge_runtime'
  ] LOOP
    -- pg_roles masks rolpassword even for the privileged operator. pg_authid
    -- gives the transaction a real password-retirement proof rather than a
    -- misleading view-level placeholder.
    IF EXISTS(SELECT 1 FROM pg_authid WHERE rolname=r AND (rolcanlogin OR rolpassword IS NOT NULL))
      OR EXISTS(SELECT 1 FROM pg_auth_members edge JOIN pg_roles granted ON granted.oid=edge.roleid
                 JOIN pg_roles member ON member.oid=edge.member WHERE granted.rolname=r OR member.rolname=r) THEN
      RAISE EXCEPTION 'Runtime login or authority survives retirement: %',r;
    END IF;
  END LOOP;
END $postflight$;
COMMIT;
`

if (process.argv.includes('--check')) {
  let current = ''
  try { current = await readFile(output, 'utf8') } catch { /* mismatch below */ }
  if (current !== sql) { console.error('staging account activation recovery artifact is stale'); process.exitCode = 1 }
} else await writeFile(output, sql, { mode: 0o644 })
