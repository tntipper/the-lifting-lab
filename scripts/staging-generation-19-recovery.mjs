#!/usr/bin/env node
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const root=resolve(import.meta.dirname,'..')
const predecessor=Object.freeze({generation:6,windowId:'83888906-23fa-4653-a886-fe2733ed76a0'})
const successor=Object.freeze({generation:19,windowId:'51809dd4-bd4b-44c7-8609-7dd8ca063679'})
const files=Object.freeze([
  Object.freeze({source:'config/staging-account-activation-recovery.sql',sourceSha256:'69b6cae3da32c62512008e14c3fb6c68746e9ee533a1dedcaa690ff349fea87c',output:'config/staging-generation-19-recovery.sql'}),
  Object.freeze({source:'config/staging-account-activation-recovery-postcommit.sql',sourceSha256:'278953bd725c9ccdba2e2da0faaafac76aafd94e65234e1fa0c62d68b1d78d35',output:'config/staging-generation-19-recovery-postcommit.sql'}),
])
const unavailable=()=>{throw new Error('Generation-19 recovery generation unavailable')}

function replaceRequired(value,from,to){if(!value.includes(from))unavailable();return value.replaceAll(from,to)}
function transform(value){
  const isPostCommit=value.includes('-- Run after recovery in a fresh session as the same reviewed staging operator.')
  value=replaceRequired(value,'-- GENERATED by scripts/staging-account-activation-recovery.mjs; do not edit.','-- GENERATED by scripts/staging-generation-19-recovery.mjs from the pinned generation-6 recovery; do not edit.')
  value=replaceRequired(value,`parsed->>'generation' IS DISTINCT FROM '${predecessor.generation}'`,`parsed->>'generation' IS DISTINCT FROM '${successor.generation}'`)
  if(value.includes(`'generation',${predecessor.generation}`))value=value.replaceAll(`'generation',${predecessor.generation}`,`'generation',${successor.generation}`)
  value=replaceRequired(value,predecessor.windowId,successor.windowId)
  const operator=isPostCommit?'session_user':'operator_name'
  value=replaceRequired(value,
    "IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=r AND rolcanlogin) OR EXISTS(SELECT 1 FROM pg_auth_members e JOIN pg_roles granted ON granted.oid=e.roleid",
    `IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=r AND (rolcanlogin OR rolpassword IS NOT NULL)) OR NOT EXISTS(SELECT 1 FROM pg_auth_members e JOIN pg_roles granted ON granted.oid=e.roleid JOIN pg_roles member ON member.oid=e.member WHERE granted.rolname=r AND member.rolname=${operator} AND e.admin_option AND NOT e.inherit_option AND NOT e.set_option) THEN RAISE EXCEPTION 'Missing retired runtime ADMIN-only operator edge: %',r; END IF;\n    IF EXISTS(SELECT 1 FROM pg_auth_members e JOIN pg_roles granted ON granted.oid=e.roleid`
  )
  value=replaceRequired(value,
    "    IF EXISTS(SELECT 1 FROM pg_auth_members e JOIN pg_roles granted ON granted.oid=e.roleid",
    `    IF EXISTS(
      SELECT 1 FROM pg_namespace n CROSS JOIN LATERAL aclexplode(n.nspacl) a WHERE n.nspname LIKE 'tll\\_%\\_private' ESCAPE '\\' AND a.grantee=0 AND a.privilege_type='USAGE'
      UNION ALL SELECT 1 FROM pg_namespace n CROSS JOIN LATERAL aclexplode(n.nspacl) a JOIN pg_roles g ON g.oid=a.grantee WHERE n.nspname LIKE 'tll\\_%\\_private' ESCAPE '\\' AND g.rolname=r
      UNION ALL SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace CROSS JOIN LATERAL aclexplode(c.relacl) a JOIN pg_roles g ON g.oid=a.grantee WHERE n.nspname LIKE 'tll\\_%\\_private' ESCAPE '\\' AND g.rolname=r
      UNION ALL SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace CROSS JOIN LATERAL aclexplode(p.proacl) a JOIN pg_roles g ON g.oid=a.grantee WHERE n.nspname LIKE 'tll\\_%\\_private' ESCAPE '\\' AND g.rolname=r) THEN RAISE EXCEPTION 'Direct private authority survives retirement: %',r; END IF;
    IF EXISTS(SELECT 1 FROM pg_auth_members e JOIN pg_roles granted ON granted.oid=e.roleid`
  )
  if(isPostCommit){
    value=replaceRequired(value,'END $zero_runtime_sessions$;\nCOMMIT;\n',`  IF (SELECT count(*) FROM tll_customer_private.control)<>1 OR EXISTS(SELECT 1 FROM tll_customer_private.control WHERE NOT singleton OR enabled)
    OR (SELECT count(*) FROM tll_cart_private.control)<>1 OR EXISTS(SELECT 1 FROM tll_cart_private.control WHERE NOT singleton OR enabled)
    OR (SELECT count(*) FROM tll_broker_private.control)<>1 OR EXISTS(SELECT 1 FROM tll_broker_private.control WHERE NOT singleton OR enabled)
    OR (SELECT count(*) FROM tll_provisional_private.control)<>1 OR EXISTS(SELECT 1 FROM tll_provisional_private.control WHERE NOT singleton OR enabled)
    OR (SELECT count(*) FROM tll_bridge_private.control)<>1 OR EXISTS(SELECT 1 FROM tll_bridge_private.control WHERE NOT singleton OR enabled) THEN
    RAISE EXCEPTION 'Post-commit controls are not exact-singleton disabled';
  END IF;
END $zero_runtime_sessions$;
COMMIT;
`)
    value=replaceRequired(value,'COMMIT;\n',`COMMIT;
SELECT jsonb_build_object('queryId','tll-staging-generation-19-retirement-postcommit/v1','projectRef','qdmvngjwkcsilzmqksme','generation',19,'windowId','${successor.windowId}','status','PASS_RETIRED','runtimeRoles',5,'runtimeSessions',0,'controlsEnabled',0,'passwordsConfigured',0,'executionEdges',0,'operatorEdges',5) AS tll_gen19_retirement_postcommit;
`)
  }
  if(value.includes(predecessor.windowId)||value.includes(`parsed->>'generation' IS DISTINCT FROM '${predecessor.generation}'`))unavailable()
  return value
}

const outputs=[]
for(const file of files){
  const source=await readFile(resolve(root,file.source),'utf8')
  if(createHash('sha256').update(source).digest('hex')!==file.sourceSha256)unavailable()
  outputs.push([resolve(root,file.output),transform(source)])
}
if(process.argv.includes('--check')){
  let stale=false
  for(const [path,expected] of outputs){let current='';try{current=await readFile(path,'utf8')}catch{}if(current!==expected)stale=true}
  if(stale){console.error('generation-19 recovery artifact is stale');process.exitCode=1}
}else for(const [path,content] of outputs)await writeFile(path,content,{mode:0o644})
