const unavailable = () => { throw new Error('Generation 20 retirement preflight unavailable') }
export function validateResult (rows) {
  if (!Array.isArray(rows) || rows.length !== 1 || Object.keys(rows[0] ?? {}).join('|') !== 'tll_gen20_retirement_preflight') unavailable()
  const receipt = rows[0].tll_gen20_retirement_preflight
  const keys = ['controlsEnabled', 'credentialState', 'executionEdges', 'generation', 'migrations', 'operatorEdges', 'projectRef', 'queryId', 'runtimeRoles', 'runtimeSessions', 'status', 'windowId', 'workCounts']
  if (!receipt || typeof receipt !== 'object' || Array.isArray(receipt) || Object.keys(receipt).sort().join('|') !== keys.sort().join('|')) unavailable()
  if (receipt.queryId !== QUERY_ID || receipt.projectRef !== PROJECT_REF || receipt.generation !== GENERATION || receipt.windowId !== WINDOW_ID || receipt.status !== 'PASS_EXACT_ACTIVE_BOUNDED' || receipt.credentialState !== 'ACTIVE_BOUNDED_FINITE') unavailable()
  if (receipt.migrations !== migrations.length || receipt.runtimeRoles !== 5 || receipt.runtimeSessions !== 0 || receipt.controlsEnabled !== 5 || receipt.executionEdges !== 5 || receipt.operatorEdges !== 5) unavailable()
  const workKeys = ['accountLogouts', 'accountOperations', 'bridgeFinalizations', 'bridgeGrants', 'brokerFlows', 'cartOperations', 'cartSessions', 'cartTransitions', 'provisionalIntents', 'shopifyProofs']
  if (!receipt.workCounts || Object.keys(receipt.workCounts).sort().join('|') !== workKeys.sort().join('|')) unavailable()
  for (const [name, counts] of Object.entries(receipt.workCounts)) {
    if (name === 'accountLogouts') { if (!Number.isInteger(counts) || counts < 0) unavailable(); continue }
    if (!counts || typeof counts !== 'object' || Array.isArray(counts) || Object.values(counts).some(count => !Number.isInteger(count) || count < 0)) unavailable()
  }
  return Object.freeze({ status: 'PASS', target: PROJECT_REF, queryId: QUERY_ID, receiptHash: createHash('sha256').update(JSON.stringify(receipt)).digest('hex'), receipt: Object.freeze(receipt) })
}

